#!/usr/bin/env python3
"""Characterize fixed area-model primitives outside candidate search."""
import argparse
from decimal import Decimal
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / "benchmarks/rtl/MutexShare-Case-Set/lib/gscl45nm.lib"

def write_area_header(model_path):
    model = json.loads(model_path.read_text(), parse_float=Decimal)
    max_width, area = model["max_width"], model["area"]
    # Yosys stat -json writes six decimal places for Liberty area.
    scale = 10**6

    def units(name):
        value = area[name] * scale
        if value != int(value):
            raise ValueError(f"{name} area exceeds stat -json precision")
        return str(int(value))

    header = ["// Generated by characterize_area.py; do not edit.",
              "// Evidence: " + str(model_path.relative_to(ROOT)),
              "// Liberty SHA256: " + model["inputs_sha256"][str(LIB.relative_to(ROOT))],
              "#pragma once", "#include <cstdint>",
              "namespace xls_share { namespace characterized {",
              f"inline constexpr int scale = {scale};"]
    for name in ("inv", "and2", "or2", "xor2", "mux2", "fa"):
        header.append(f"inline constexpr std::int64_t {name} = {units(name)};")
    header += [f"inline constexpr int max_width = {max_width};",
               "inline constexpr std::int64_t add[] = {0, " +
               ", ".join(units(f"add{w}") for w in range(1, max_width+1)) + "};",
               "}}"]
    (ROOT / "src/xls_share/area_model.h").write_text("\n".join(header) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    inputs = sorted((ROOT / "benchmarks/rtl/MutexShare-Case-Set/case").glob("*/tc.v"))
    max_width = max(abs(int(a)-int(b))+1 for p in inputs
                    for a, b in re.findall(r"\[(\d+)\s*:\s*(\d+)\]", p.read_text()))
    modules = {
        "inv": "input a; output y; assign y = ~a;",
        "and2": "input a,b; output y; assign y = a & b;",
        "or2": "input a,b; output y; assign y = a | b;",
        "xor2": "input a,b; output y; assign y = a ^ b;",
        "mux2": "input a,b,s; output y; assign y = s ? b : a;",
        "fa": "input a,b,c; output [1:0] y; assign y[0]=(a^b)^c; assign y[1]=(a&b)|(c&(a^b));",
    }
    for width in range(1, max_width + 1):
        modules[f"add{width}"] = (f"input [{width-1}:0] a,b; output [{width-1}:0] y; "
                                  "assign y=a+b;")
    rtl = out / "templates.v"
    texts = []
    for name, body in modules.items():
        ports = re.findall(r"(?:input|output) (?:\[[^]]+\] )?([^;]+)", body)
        names = ",".join(ports).replace(" ", "")
        texts.append(f"module {name}({names}); {body} endmodule")
    rtl.write_text("\n".join(texts) + "\n")
    yosys, abc = ROOT / "tools/local/bin/yosys", ROOT / "tools/abc/abc"
    commands = [f'read_verilog "{rtl}"', "design -save templates"]
    for name in modules:
        commands += ["design -load templates", f"hierarchy -top {name}",
                     f"rename {name} tc", "synth -top tc -noabc",
                     f'abc -exe "{abc}" -liberty "{LIB}"', "clean",
                     f'tee -o "{out / (name + ".json")}" stat -json -liberty "{LIB}"']
    script = out / "flow.ys"
    script.write_text("\n".join(commands) + "\n")
    begin = time.monotonic()
    with (out / "yosys.log").open("w") as log:
        subprocess.run([str(yosys), "-s", str(script)], stdout=log,
                       stderr=subprocess.STDOUT, check=True, cwd=out)
    area = {}
    for name in modules:
        report = json.loads((out / (name + ".json")).read_text())["design"]
        area[name] = report["area"] - report["sequential_area"]
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    report = {"max_width": max_width, "area": area, "elapsed_s": time.monotonic()-begin,
              "physical_cpus": sorted(os.sched_getaffinity(0)),
              "inputs_sha256": {str(p.relative_to(ROOT)): sha(p) for p in [LIB, yosys, abc, Path(__file__).resolve()]},
              "templates_sha256": sha(rtl),
              "dataset_rtl_sha256": hashlib.sha256("".join(sha(p) for p in inputs).encode()).hexdigest(),
              "yosys_version": subprocess.check_output([str(yosys), "-V"], text=True).strip()}
    (out / "model.json").write_text(json.dumps(report, indent=2) + "\n")
    write_area_header(out / "model.json")
    print(json.dumps({"max_width": max_width, "templates": len(area),
                      "elapsed_s": report["elapsed_s"], "primitive_areas": {k: area[k] for k in list(modules)[:6]}}))

if __name__ == "__main__":
    main()
